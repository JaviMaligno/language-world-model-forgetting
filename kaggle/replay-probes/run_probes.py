# Phase 4: does replay also win back instruction-following (IFEval) and OOD simulation?
# Phase 3 measured IFEval and the hard (OOD) terminal set only at mix0. Here: Qwen2.5-0.5B-Instruct,
# full fine-tuning, mix00 / mix10 / mix25, 3 seeds each, same configs as Phases 1 and 3, full test
# sets. Two queues, one per T4. Progress every 5 min; each result JSON is saved as soon as its run ends.
import glob, json, os, subprocess, sys, time

T0 = time.time()
W = "/kaggle/working"
REPO = f"{W}/lwmf"

def log(msg):
    print(f"[{(time.time() - T0) / 60:6.1f} min] {msg}", flush=True)

def sh(cmd, **kw):
    log(f"$ {cmd}")
    subprocess.run(cmd, shell=True, check=True, **kw)

sh(f"git clone -q https://github.com/JaviMaligno/language-world-model-forgetting {REPO}")
os.chdir(REPO)
sh("git log --oneline -1")
sh("pip install -q -e '.[gpu]' langdetect immutabledict nltk 2>&1 | tail -3")
sh("python -c \"import nltk; nltk.download('punkt', quiet=True); nltk.download('punkt_tab', quiet=True)\"")
sh("python -c \"from lm_eval.tasks.ifeval import instructions_util as u; print('ifeval deps OK, words:', u.count_words('One line, please. Two sentences here.'))\"")
sh("nvidia-smi --query-gpu=name,memory.total --format=csv")

os.makedirs("data", exist_ok=True)
pre = sorted(glob.glob("/kaggle/input/**/train.jsonl", recursive=True))
if pre:  # dataset lwmf-probe-data: the exact files generated by version 1 (same seeds), saves ~75 min
    src = os.path.dirname(pre[0])
    sh(f"cp {src}/train.jsonl {src}/heldout.jsonl {src}/heldout_hard.jsonl {src}/replay.jsonl data/ && wc -l data/*.jsonl")
else:
    sh("python -c \"from lwmf.data.terminal_gen import generate_trajectories as g; "
       "print(g('data/train.jsonl', 28000, 0, '/tmp/boxes')); print(g('data/heldout.jsonl', 600, 99, '/tmp/boxes_ho'))\"")
    sh("python -c \"from lwmf.data.terminal_gen import generate_trajectories as g, build_scenario_hard as h; "
       "print(g('data/heldout_hard.jsonl', n_scenarios=400, seed=123, scratch_root='/tmp/boxes_hard', scenario_fn=h))\"")
    sh("python scripts/fetch_replay.py data/replay.jsonl 12000")
log("data ready")

QUEUES = {
    0: [("mix10", 0), ("mix10", 2), ("mix25", 1), ("mix00", 0), ("mix00", 2)],
    1: [("mix10", 1), ("mix25", 0), ("mix25", 2), ("mix00", 1)],
}
TOTAL = sum(len(q) for q in QUEUES.values())

worker = r'''
import os, subprocess, sys, time
gpu, items = sys.argv[1], sys.argv[2:]
for it in items:
    mix, seed = it.split(":")
    t = time.time()
    out = f"results/kaggle/{mix}-seed{seed}"
    os.makedirs(out, exist_ok=True)
    print(f"GPU{gpu} START {mix} seed{seed}", flush=True)
    r = subprocess.run([sys.executable, "-m", "lwmf.run", "--config", f"configs/phase1_05B_instruct_{mix}.yaml",
                        "--seed", seed, "--terminal-train", "data/train.jsonl", "--terminal-heldout", "data/heldout.jsonl",
                        "--terminal-heldout-hard", "data/heldout_hard.jsonl", "--results-dir", out])
    print(f"GPU{gpu} END {mix} seed{seed} rc={r.returncode} in {(time.time()-t)/60:.1f} min", flush=True)
'''
open("/tmp/worker.py", "w").write(worker)
procs = []
for gpu, q in QUEUES.items():
    env = {**os.environ, "CUDA_VISIBLE_DEVICES": str(gpu), "LWMF_REPLAY_FILE": f"{REPO}/data/replay.jsonl",
           "PYTORCH_CUDA_ALLOC_CONF": "expandable_segments:True", "TOKENIZERS_PARALLELISM": "false"}
    lf = open(f"{W}/gpu{gpu}.log", "w")
    procs.append((gpu, subprocess.Popen([sys.executable, "/tmp/worker.py", str(gpu)] + [f"{m}:{s}" for m, s in q],
                                        env=env, stdout=lf, stderr=subprocess.STDOUT), lf))
log(f"launched {TOTAL} runs on 2 GPUs")

def tail(path, n=2):
    try:
        lines = [l.strip() for l in open(path, errors="ignore").read().replace("\r", "\n").splitlines() if l.strip()]
        return " | ".join(lines[-n:])[-300:]
    except OSError:
        return "-"

while any(p.poll() is None for _, p, _ in procs):
    time.sleep(300)
    done = len(glob.glob("results/kaggle/*/*.json"))
    el = (time.time() - T0) / 60
    log(f"PROGRESS {done}/{TOTAL} runs saved")
    for gpu, p, _ in procs:
        ev = [l for l in open(f"{W}/gpu{gpu}.log", errors="ignore").read().splitlines() if l.startswith(f"GPU{gpu} ")]
        log(f"  GPU{gpu}: {ev[-1] if ev else 'starting'} :: {tail(f'{W}/gpu{gpu}.log')}")
    os.makedirs(f"{W}/results", exist_ok=True)
    sh(f"cp -r results/kaggle/. {W}/results/ 2>/dev/null || true")

sh(f"cp -r results/kaggle/. {W}/results/ && cp docs/EXPERIMENTS.md {W}/EXPERIMENTS-appended.md")
for gpu, p, lf in procs:
    lf.close()
    log(f"GPU{gpu} exit {p.returncode}")
log(f"DONE: {len(glob.glob(f'{W}/results/*/*.json'))}/{TOTAL} result files")
